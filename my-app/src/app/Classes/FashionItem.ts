// Exercise 58 - data structure of one document in collection "Fashion"
export interface FashionItem {
  _id?: string               // ObjectId generated by MongoDB
  IdF?: number               // unique numeric id (1, 2, 3...) generated by the server
  slug?: string              // e.g. "street-style-look-p3" (title + "-p" + IdF)
  fashion_subject: string    // fashion title
  fashion_detail: string     // fashion details (HTML from WYSIWYG editor)
  fashion_image: string      // thumbnail (base64 data URL)
  style: string              // Fashion's Style
  created_date?: string      // creation date
}
